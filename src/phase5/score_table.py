def main():
    with open(ROOT / "src" / "phase5" / "eval_answers.json", encoding="utf-8") as f:
        questions = json.load(f)

    out_path = ROOT / "data" / "score_table.csv"
    rows = []
    for question in questions:
        for condition in ["S", "A", "B"]:
            key = (question["id"], condition)
            if key not in SCORES:
                continue
            correct, source_match, conflict, invented, note = SCORES[key]
            rows.append([question["id"], question["kind"], condition, correct, source_match, conflict, invented, note])

    with open(out_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["id", "종류", "조건", "정답", "출처일치", "사전내충돌", "지어냄", "비고"])
        writer.writerows(rows)
    print(len(rows), "행 →", out_path)


if __name__ == "__main__":
    main()
